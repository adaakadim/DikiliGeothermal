"""
analytics/decision_support/recommendation_prioritizer.py
========================================================
Sorts and ranks actions generated by various AI engines.
"""

from typing import List, Dict, Any

class RecommendationPrioritizer:
    def prioritize(self, opt_recs: list, maint_recs: list, risk_assessments: dict) -> List[Dict[str, Any]]:
        """
        Combines optimization recommendations and maintenance recommendations,
        sorting them by severity and priority.
        """
        unified_recs = []
        
        # Add Optimization Recs
        for rec in opt_recs:
            unified_recs.append({
                "source": "Optimization Engine",
                "equipment": rec.get("Equipment", "Unknown"),
                "action": rec.get("Suggestion", "Optimize Process"),
                "impact": f"Efficiency +{rec.get('Estimated Improvement', '0%')}",
                "priority": "LOW", # Usually optimizations are lower priority than failures
                "score": 20
            })
            
        # Add Maintenance Recs based on fused risk
        for eq_id, assessment in risk_assessments.items():
            priority = assessment.get("Maintenance Priority", "LOW")
            if priority != "LOW":
                score = 100 if priority == "CRITICAL" else (80 if priority == "HIGH" else 50)
                unified_recs.append({
                    "source": "Predictive Maintenance",
                    "equipment": eq_id,
                    "action": assessment.get("Recommended Action", "Inspect"),
                    "impact": f"Prevent Failure ({assessment.get('Overall Risk')})",
                    "priority": priority,
                    "score": score
                })
                
        # Sort by score descending
        unified_recs.sort(key=lambda x: x["score"], reverse=True)
        return unified_recs
